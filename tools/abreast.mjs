// Classify every placement of a second free ship beside a first, flying the same way,
// and write site/js/abreast.js. tests/abreast.test.mjs checks every entry
// independently, so this script is a convenience, not an authority.
// Usage: node tools/abreast.mjs > site/js/abreast.js.new && mv site/js/abreast.js.new site/js/abreast.js
import fs from 'node:fs';
import { Pattern } from '../site/js/lfod.js';
import { shipPairOutcome } from './../tests/objects.mjs';
import { SHIP, SHIP_E as E, SHIP_DY as DY, shipPair, shipB } from '../site/js/abreast.js';

const MAP = [], OUT = {};
const fleet = new Map(); // object key -> entry
const key = (cells, f) => {
  cells = cells.map(([x, y]) => [x, f ? -y : y]);
  const mx = Math.min(...cells.map((c) => c[0])), my = Math.min(...cells.map((c) => c[1]));
  return cells.map(([x, y]) => `${x - mx},${y - my}`).sort().join(';');
};
for (let ph = 0; ph < 6; ph++) {
  const rows = [];
  for (let dy = 0; dy <= DY; dy++) {
    let row = '';
    for (let e = -E; e <= E; e++) {
      const o = shipPairOutcome(ph, e, dy);
      if (!o) { row += ' '; continue; }
      if (o.kind === 'apart') { row += '.'; continue; }
      if (o.kind === 'explodes') { row += '#'; continue; }
      row += 'o';
      const k = `${ph},${e},${dy}`;
      if (o.kind === 'nothing') OUT[k] = `${o.at}:nothing`;
      else if (o.kind === 'objects') {
        const order = ['freeship', 'moon', 'checker', 'dot'];
        const names = Object.keys(o.objects).sort((a, b) => order.indexOf(a) - order.indexOf(b));
        OUT[k] = `${o.at}:` + names.map((n) => (o.objects[n] > 1 ? `${n}×${o.objects[n]}` : n)).join(' ');
      } else {
        // which distinct flotilla or puffer: the leading 20 columns of each phase, up to a flip
        let p = Pattern.fromCells(shipPair(ph, e, dy));
        for (let g = 0; g < 120; g++) p = p.next();
        const ks = [];
        for (let g = 0; g < 6; g++, p = p.next()) {
          const R = p.x0 + p.w - 1, front = p.cells().filter(([x]) => x > R - 20);
          ks.push(key(front, 0), key(front, 1));
        }
        const id = ks.sort()[0];
        if (!fleet.has(id)) fleet.set(id, { kind: o.kind, ph, e, dy, at: o.at, wake: o.wake, also: [] });
        else fleet.get(id).also.push([ph, e, dy]);
        OUT[k] = `${o.at}:${o.kind}`;
      }
    }
    rows.push(row);
  }
  MAP.push(rows);
  console.error('phase', ph);
}
// `clean`: the generations of each period (mod 6) at which the pattern is exactly the
// two ships as they would be alone, plus cells that are all still there 6 and 12
// generations later (a frozen wake); `rows`: every row it ever occupies
function cleanAt(G, g, A, B) {
  const has = (p) => { const s = new Set(p.cells().map((c) => c.join())); return (c) => s.has(c.join()); };
  const now = has(G[g]), later = has(G[g + 6]), later2 = has(G[g + 12]);
  const ships = [...A.cells(), ...B.cells()], u = new Set(ships.map((c) => c.join()));
  return ships.every(now) && G[g].cells().every((c) => u.has(c.join()) || (later(c) && later2(c)));
}
const ORDER = { flotilla: 0, puffer: 1 };
const FLEET = [...fleet.values()].map((f) => {
  // show the mirror image with e >= 0 where there is one
  const all = [[f.ph, f.e, f.dy], ...f.also].sort((a, b) => Math.abs(a[1]) - Math.abs(b[1]) || b[1] - a[1] || a[0] - b[0]);
  const [ph, e, dy] = all[0];
  const G = [Pattern.fromCells(shipPair(ph, e, dy))];
  for (let g = 1; g < 400; g++) G.push(G[g - 1].next());
  let A = Pattern.fromCells(SHIP[0]), B = Pattern.fromCells(shipB(ph, e, dy));
  let lo = Infinity, hi = -Infinity; const clean = [];
  for (let g = 0; g < 380; g++) {
    lo = Math.min(lo, G[g].y0); hi = Math.max(hi, G[g].y0 + G[g].h - 1);
    if (g >= 120 && g < 126 && cleanAt(G, g, A, B)) clean.push(g % 6);
    A = A.next(); B = B.next();
  }
  const out = { kind: f.kind, ph, e, dy, at: shipPairOutcome(ph, e, dy).at };
  if (f.wake) out.wake = f.wake;
  return { ...out, also: all.slice(1), clean, rows: [lo, hi] };
}).sort((a, b) => ORDER[a.kind] - ORDER[b.kind] || b.clean.length - a.clean.length || a.ph - b.ph || a.dy - b.dy);

const src = fs.readFileSync(new URL('../site/js/abreast.js', import.meta.url), 'utf8');
const head = src.slice(0, src.indexOf('// ---- generated'));
const j = (v) => JSON.stringify(v);
console.log(head + `// ---- generated by tools/abreast.mjs (everything below; checked by tests/abreast.test.mjs)
// MAP[ph][dy] has one character for each e from -E to E: ' ' the ships overlap, '.' they
// never touch, '#' explodes, 'o' see OUT. Mirror images (dy and -dy) share an entry.
export const MAP = [
${MAP.map((rows) => '  [\n' + rows.map((r) => `    ${j(r)},`).join('\n') + '\n  ],').join('\n')}
];

// 'ph,e,dy' -> 'at:objects' in the collision atlas's notation (from generation \`at\`,
// and not before, exactly those objects, which never meet again), 'at:nothing',
// 'at:flotilla' or 'at:puffer' (see FLEET).
export const OUT = {
${Object.entries(OUT).map(([k, v]) => `  '${k}': '${v}',`).join('\n')}
};

// The distinct flotillas and puffers, each at its first placement (ph, e, dy) and the
// others that make the same object (\`also\`). \`clean\`: the generations (mod 6) at which
// the leading 20 columns are exactly the two ships run alone. \`rows\`: every row it ever
// occupies. \`wake\`: what a puffer lays down every 6 generations.
export const FLEET = [
${FLEET.map((f) => '  ' + j(f) + ',').join('\n')}
];
`);
