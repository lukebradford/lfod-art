// Classify every placement of two parallel dominoes (the second with its top cell at
// (dx, dy) from the first, 0 <= dx <= LON, 0 <= dy <= LAT) and write site/js/dominoes.js.
// tests/dominoes.test.mjs checks every entry independently, so this script is a
// convenience, not an authority. Usage: node tools/dominoes.mjs > site/js/dominoes.js
import { dominoOutcome } from '../tests/objects.mjs';

const LAT = 12, LON = 36;
const rows = [];
for (let dy = 0; dy <= LAT; dy++) {
  const row = [];
  for (let dx = 0; dx <= LON; dx++) {
    if (dx === 0 && dy <= 1) { row.push(''); continue; } // overlapping
    const o = dominoOutcome(dx, dy);
    row.push(o === 'explodes' ? '#' : o === 'apart' ? '.' : o === null ? 'puffers' : o);
  }
  rows.push(row);
  console.error('row', dy);
}
const json = (r) => '  [' + r.map((s) => JSON.stringify(s)).join(', ') + '],';
console.log(`// Two dominoes: what happens when a second vertical domino is placed anywhere near a
// first. Generated by tools/dominoes.mjs; every entry is checked by
// tests/dominoes.test.mjs, which runs every placement.
//
// The first domino is (0, 0), (0, 1). MAP[dy][dx] is the outcome when the second has its
// top cell at (dx, dy). Mirror images are the same placement, so (±dx, ±dy) all share
// MAP[|dy|][|dx|]. Entries: '' the dominoes overlap; '#' explodes; '.' they never touch
// (each runs exactly as it would alone); 'at:objects' in the collision atlas's notation:
// from generation \`at\` (never before 12, when a lone domino has parted) the pattern is
// exactly those objects, the ships among them flying exactly as they would alone, and
// none of them ever meets another; 'puffers' grows forever (see DUEL).
export const LAT = ${LAT}, LON = ${LON};

export const MAP = [
${rows.map(json).join('\n')}
];

// The glossary's dueling dominoes (its RLE verbatim), turned here so its puffers fly
// left and right. Neither domino is ever disturbed: at every generation the pattern is
// exactly the two run alone, plus dots on the row halfway between them, the first in
// the middle at generation FIRST, then one more on each side every PERIOD generations.
export const DUEL = {
  dx: 2, dy: 11, first: 10, period: 6,
  rle: 'x = 13, y = 3, rule = s0/b2\\n11b2o2$2o!',
  url: 'https://lukebradford.github.io/lfod/glossary.html#dueling-dominoes',
};

export const pairCells = (dx, dy) => [[0, 0], [0, 1], [dx, dy], [dx, dy + 1]];
export const outcomeAt = (dx, dy) => MAP[Math.abs(dy)]?.[Math.abs(dx)];
`);
