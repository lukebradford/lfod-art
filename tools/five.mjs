// Classify every placement of five cells (each within two of another, up to symmetry)
// and write site/js/five.js. Takes about a minute. tests/five.test.mjs checks every
// line of the output independently, so this script is a convenience, not an authority.
// Usage: node tools/five.mjs > site/js/five.js
import { Pattern } from '../site/js/lfod.js';
import { extend, placements, canon, norm, decompose, tally, orient, explodes, puffer } from '../tests/objects.mjs';

const t0 = Date.now();
const all = extend(placements(4));
const log = (...a) => console.error(...a, `(${((Date.now() - t0) / 1000).toFixed(1)} s)`);
log(all.length, 'placements');

// biggest first, as phrase() reads them
const RANK = ['monster', 'freeship', 'moon', 'anchor', 'lever', 'radar', 'ant', 'checker', 'dot'];
const enc = (cells) => cells.map(([x, y]) => `${x}${y}`).join('');
const settle = [], vanish = [], puffs = [], late = [];
let boom = 0;
for (const cells of all) {
  // quick look first: vanished or still small after 60 generations?
  let p = Pattern.fromCells(cells), gone = 0;
  for (let g = 1; g <= 60 && !gone; g++) { p = p.next(); if (!p.population) gone = g; }
  if (gone) { vanish.push([enc(cells), gone]); continue; }
  if (p.population > 150 || explodes(cells)) {
    if (!explodes(cells)) {
      // slow to catch: measure the same way from generation 200
      if (!explodes(cells, 200)) throw new Error('large but not explosive: ' + enc(cells));
      late.push(enc(cells));
    }
    boom++; continue;
  }
  let q = Pattern.fromCells(cells), at = -1;
  for (let g = 0; g <= 120; g++, q = q.next()) if (decompose(q)) { at = g; break; }
  if (at >= 0) {
    const t = tally(decompose(q));
    if (!Object.keys(t).length) throw new Error('vanished late: ' + enc(cells));
    const s = Object.entries(t).sort((a, b) => RANK.indexOf(a[0]) - RANK.indexOf(b[0]))
      .map(([k, n]) => (n > 1 ? `${k}×${n}` : k)).join(' ');
    settle.push([enc(cells), `${at}:${s}`]);
    continue;
  }
  // a puffer? turn it to travel right (or, for a pair, left and right)
  let found = null;
  for (const f of [0, 1]) for (let r = 0; r < 4 && !found; r++) {
    const c = norm(orient(cells, f, r));
    const res = puffer(c);
    if (res) found = [c, res];
  }
  if (!found) throw new Error('unclassified: ' + enc(cells));
  puffs.push([enc(found[0]), `${found[1].at}:puffer${found[1].n > 1 ? '×' + found[1].n : ''}`]);
}
log('explode', boom, 'vanish', vanish.length, 'settle', settle.length, 'puff', puffs.length);

const order = (s) => +s.split(':')[0];
settle.sort((a, b) => a[1].split(':')[1].localeCompare(b[1].split(':')[1]) || order(a[1]) - order(b[1]) || a[0].localeCompare(b[0]));
vanish.sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]));
puffs.sort((a, b) => order(a[1]) - order(b[1]) || a[0].localeCompare(b[0]));
const rows = (list) => list.map(([c, o]) => `  ['${c}', ${typeof o === 'number' ? o : `'${o}'`}],`).join('\n');

console.log(`// Five cells: every way to place five cells close enough to meet (each within two of
// another), counted once up to rotation and reflection, and what becomes of each.
// Generated by tools/five.mjs. Every line is checked by tests/five.test.mjs, which
// enumerates the placements itself and runs every one.
//
// Cells are written as digit pairs, x then y, with the top-left at (0, 0): '0011' is
// the cells (0, 0) and (1, 1). Outcomes use the collision atlas's notation, 'at:objects':
// at generation \`at\` the pattern is exactly those objects, far enough apart never to
// meet again, and not yet so at \`at - 1\`. 'puffer' is the double dot puffer: from
// generation \`at\` on, the pattern is that puffer flying right at c with a frozen wake,
// and is not yet so at \`at - 1\`. PUFF placements are turned so their puffers fly
// right (or, for the pair, left and right); the others are in canonical orientation.

// Those in LATE explode only by the same standard measured from generation 200.
export const FIVE = { placements: ${all.length}, explode: ${boom} };
export const LATE = ${JSON.stringify(late)};

export const cellsOf = (s) => Array.from({ length: s.length / 2 }, (_, i) => [+s[2 * i], +s[2 * i + 1]]);

export const PUFF = [
${rows(puffs)}
];

export const SETTLE = [
${rows(settle)}
];

export const VANISH = [
${rows(vanish)}
];`);
log('done');
