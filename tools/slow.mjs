// Writes site/js/slow.js: every ship in the LFoD Universe glossary that travels slower
// than light, with its RLE copied verbatim from the glossary page and its period,
// displacement and population range measured by simulation. tests/slow.test.mjs checks
// every number again against the engine, so this script is a convenience, not an
// authority.
//
//   node tools/slow.mjs ~/Dropbox/Code/lfod/docs/glossary.html
import fs from 'node:fs';
import { Pattern, classify } from '../site/js/lfod.js';

const src = process.argv[2];
if (!src) { console.error('usage: node tools/slow.mjs path/to/glossary.html'); process.exit(1); }
const html = fs.readFileSync(src, 'utf8');
const unescape = (s) => s.replace(/&quot;/g, '"').replace(/&#39;|&#x27;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

// Tagalongs are shown riding a ship; they are not ships in their own right.
const SKIP = new Set(['buffalo-bird']);

const ships = [];
for (const m of html.matchAll(/<article class="entry" id="([^"]+)" data-kind="([^"]*)"([\s\S]*?)<\/article>/g)) {
  const [, id, , body] = m;
  if (SKIP.has(id)) continue;
  const rle = body.match(/data-rle="([^"]*)"/);
  if (!rle) continue;
  const text = unescape(rle[1]);
  let p;
  try { p = Pattern.fromRLE(text); } catch { continue; }
  const c = classify(p, { maxGen: 64 });
  if (c.kind !== 'ship') continue;
  const d = Math.max(Math.abs(c.dx), Math.abs(c.dy));
  if (d === c.period) continue; // the speed of light: not slow
  const name = unescape(body.match(/<h3><a[^>]*>([\s\S]*?)<\/a>/)[1]);
  const credit = unescape((body.match(/class="tag credit">([^<]*)</) || [, ''])[1]);
  const pops = [];
  let q = p;
  for (let g = 0; g < c.period; g++) { pops.push(q.population); q = q.next(); }
  ships.push({ id, name, credit, period: c.period, dx: c.dx, dy: c.dy, pop: [Math.min(...pops), Math.max(...pops)], rle: text.trim() });
}
// fastest first; diagonal after orthogonal at the same speed; then smallest first
const v = (e) => Math.max(Math.abs(e.dx), Math.abs(e.dy)) / e.period;
ships.sort((a, b) => v(b) - v(a) || Math.abs(a.dy) - Math.abs(b.dy) || a.pop[0] - b.pop[0] || a.name.localeCompare(b.name));

const body = ships.map((e) => `  {
    id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.name)}, credit: ${JSON.stringify(e.credit)},
    period: ${e.period}, dx: ${e.dx}, dy: ${e.dy}, pop: [${e.pop}],
    rle: ${JSON.stringify(e.rle)},
  },`).join('\n');

fs.writeFileSync(new URL('../site/js/slow.js', import.meta.url), `// slow.js: every ship in the Live Free or Die Universe glossary that is slower than light.
// Generated by tools/slow.mjs from the glossary page; RLEs verbatim. Every period,
// displacement and population here is checked by tests/slow.test.mjs against the engine.
import { Pattern } from './lfod.js';

export const GLOSSARY = 'https://lukebradford.github.io/lfod/glossary.html#';

// Fastest first, then smallest. dx, dy: displacement per period (all travel right, or
// right and down for the diagonal ones). pop: fewest and most cells over one period.
export const SHIPS = [
${body}
];

export const byId = (id) => SHIPS.find((e) => e.id === id);

// One lane per orthogonal speed in the race: the smallest known ship at each.
export const RACE = ['dust-mite-ship', 'zirconium-ship', 'wasp-ship', 'beachcomber-ship', 'decade-ship'];
// Every known diagonal ship.
export const DIAGONAL = ['ram-ship', 'slanted-ship', 'giraffe-ship'];

const gcd = (a, b) => (b ? gcd(b, a % b) : a);
// 'c', 'c/2', '2c/5', 'c/4 diagonal', ...
export function speed({ period, dx, dy }) {
  const d = Math.max(Math.abs(dx), Math.abs(dy)), k = gcd(d, period);
  const n = d / k, m = period / k;
  const s = (n === 1 ? 'c' : n + 'c') + (m === 1 ? '' : '/' + m);
  return dx && dy ? s + ' diagonal' : s;
}

// The box a ship covers during its first period, from generation 0 (as in its RLE).
// Each later period covers the same box moved by (dx, dy), since it is a ship.
export function extent(e) {
  let p = Pattern.fromRLE(e.rle), x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (let g = 0; g < e.period; g++) {
    x0 = Math.min(x0, p.x0); y0 = Math.min(y0, p.y0);
    x1 = Math.max(x1, p.x0 + p.w - 1); y1 = Math.max(y1, p.y0 + p.h - 1);
    p = p.next();
  }
  return { x0, y0, x1, y1 };
}
`);
