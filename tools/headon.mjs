// Classify every way two free ships can meet head-on and write site/js/headon.js.
// tests/headon.test.mjs checks every entry independently, so this script is a
// convenience, not an authority.
// Usage: node tools/headon.mjs > site/js/headon.js.new && mv site/js/headon.js.new site/js/headon.js
import fs from 'node:fs';
import { Pattern } from '../site/js/lfod.js';
import { headOnOutcome } from '../tests/objects.mjs';
import { X0, T, DY, headPair } from '../site/js/headon.js';

const shape = (cells) => {
  const mx = Math.min(...cells.map((c) => c[0])), my = Math.min(...cells.map((c) => c[1]));
  return cells.map(([x, y]) => `${x - mx},${y - my}`).sort().join(';');
};
const order = ['freeship', 'moon', 'checker', 'dot'];
const code = (o) => {
  if (o.kind === 'nothing') return `${o.at}:nothing`;
  const names = Object.keys(o.objects).sort((a, b) => order.indexOf(a) - order.indexOf(b));
  return `${o.at}:` + names.map((n) => (o.objects[n] > 1 ? `${n}×${o.objects[n]}` : n)).join(' ');
};
const MAP = [], OUT = {};
for (let dy = 0; dy <= DY; dy++) {
  let row = '';
  for (let ph = 0; ph < 6; ph++) for (let t = 0; t < T; t++) {
    const o = headOnOutcome(ph, t, dy);
    if (o.kind === 'apart') { row += '.'; continue; }
    if (o.kind === 'explodes') { row += '#'; continue; }
    row += 'o';
    OUT[`${ph},${t},${dy}`] = code(o);
    if (o.kind === 'objects' && o.objects.freeship && !(o.objects.freeship === 2 && o.through)) throw new Error(`a ship changed: ${ph} ${t} ${dy}`);
  }
  MAP.push(row);
  console.error('dy', dy, row);
}

const src = fs.readFileSync(new URL('../site/js/headon.js', import.meta.url), 'utf8');
const head = src.slice(0, src.indexOf('// ---- generated'));
const j = (v) => JSON.stringify(v);
console.log(head + `// ---- generated by tools/headon.mjs (everything below; checked by tests/headon.test.mjs)
// MAP[dy] has one character for each (ph, t), at ph * T + t: '.' they never touch, '#'
// explodes, 'o' see OUT.
export const MAP = [
${MAP.map((r) => `  ${j(r)},`).join('\n')}
];

// 'ph,t,dy' -> 'at:objects' in the collision atlas's notation (from generation \`at\`,
// and not before, exactly those objects, which never meet again) or 'at:nothing'.
// Wherever two free ships are listed they are the two that met, each exactly where and
// as it would have been alone.
export const OUT = {
${Object.entries(OUT).map(([k, v]) => `  '${k}': '${v}',`).join('\n')}
};

`);
