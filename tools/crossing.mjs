// Classify every way two free ships can cross at right angles and write
// site/js/crossing.js. tests/crossing.test.mjs checks every entry independently, so this
// script is a convenience, not an authority.
// Usage: node tools/crossing.mjs > site/js/crossing.js.new && mv site/js/crossing.js.new site/js/crossing.js
import fs from 'node:fs';
import { crossOutcome } from '../tests/objects.mjs';
import { D } from '../site/js/crossing.js';

const order = ['freeship', 'moon', 'checker', 'dot'];
export const code = (o) => {
  if (o.kind === 'nothing') return `${o.at}:nothing`;
  const names = Object.keys(o.objects).sort((a, b) => order.indexOf(a) - order.indexOf(b));
  return `${o.at}:` + names.map((n) => (o.objects[n] > 1 ? `${n}×${o.objects[n]}` : n)).join(' ') + (o.survivors.length ? ` (${o.survivors.join('')})` : '');
};
const MAP = [], OUT = {};
for (let ph = 0; ph < 6; ph++) for (let u = 0; u < 6; u++) {
  let row = '';
  for (let d = -D; d <= D; d++) {
    const o = crossOutcome(ph, u, d);
    if (o.kind === 'apart') { row += '.'; continue; }
    if (o.kind === 'explodes') { row += '#'; continue; }
    row += 'o';
    OUT[`${ph},${u},${d}`] = code(o);
    if (o.kind === 'objects' && (o.objects.freeship || 0) !== o.survivors.length) throw new Error(`a new ship: ${ph} ${u} ${d}`);
  }
  MAP.push(row);
  console.error(ph, u, row);
}

const src = fs.readFileSync(new URL('../site/js/crossing.js', import.meta.url), 'utf8');
const cut = src.indexOf('// ---- generated');
const head = cut < 0 ? src : src.slice(0, cut);
const j = (v) => JSON.stringify(v);
console.log(head.trimEnd() + `

// ---- generated by tools/crossing.mjs (everything below; checked by tests/crossing.test.mjs)
// MAP[ph * 6 + u] has one character for each d from -D to D: '.' they never touch, '#'
// explodes, 'o' see OUT.
export const MAP = [
${MAP.map((r) => `  ${j(r)},`).join('\n')}
];

// 'ph,u,d' -> 'at:objects (survivors)' in the collision atlas's notation (from generation
// \`at\`, and not before, exactly those objects, which never meet again) or 'at:nothing'.
// (A) or (B): that ship is still there, exactly where and as it would have been alone.
export const OUT = {
${Object.entries(OUT).map(([k, v]) => `  '${k}': '${v}',`).join('\n')}
};
`);
