// Side by side: a second free ship placed beside a first, both flying the same way at
// the speed of light. Every placement where they can touch is classified below.
import { Pattern } from './lfod.js';
import { byId } from './catalog.js';

// SHIP[t] is the free ship (flying +x) t generations after its 12-cell phase (the
// glossary's minimum form), placed so that phase spans columns 0..8 and rows 0..5. At
// generation t of its own run the ship is SHIP[t % 6] moved 6 * floor(t / 6) cells on.
// Ship A is SHIP[0]. Ship B is SHIP[ph] moved (e - ph, dy): `ph` generations further
// through its cycle, its lane `e` cells further along, and `dy` rows down.
// A lone ship's cells at generation g lie in columns g - 6 .. g + 8 and rows -2 .. 7
// (tested), so B's lie in columns g + e - 6 .. g + e + 8 and rows dy - 2 .. dy + 7. When
// |e| > E or |dy| > DY, two empty columns or rows always lie between them, no cell can
// see both, and they never touch: |e| <= E, |dy| <= DY covers every case.
export const E = 16, DY = 11;
export const SHIP = [];
{
  let p = Pattern.fromRLE(byId.freeship.rle);
  while (p.population !== 12) p = p.next();
  const x0 = p.x0, y0 = p.y0;
  for (let t = 0; t < 6; t++, p = p.next()) SHIP.push(p.cells().map(([x, y]) => [x - x0, y - y0]));
}
export const SHIP_E = E, SHIP_DY = DY;
export const shipB = (ph, e, dy) => SHIP[ph].map(([x, y]) => [x + e - ph, y + dy]);
export const shipPair = (ph, e, dy) => [...SHIP[0], ...shipB(ph, e, dy)];
export const outcomeAt = (ph, e, dy) => {
  const c = MAP[ph]?.[Math.abs(dy)]?.[e + E];
  return c === 'o' ? OUT[`${ph},${e},${Math.abs(dy)}`] : c;
};


// The fleet: puffers from FLEET flying together, one lane each, as a single pattern.
// Each lane is placed GAP rows below the last row the one above can ever occupy
// (FLEET[i].rows), so at least two empty rows always lie between them, no cell sees two
// lanes, and each flies exactly as it would alone (tested).
export const GAP = 4;
const PUFFS = () => FLEET.filter((f) => f.kind === 'puffer');
export function fleetLanes(list = PUFFS()) {
  let y = 0;
  return list.map((f, i) => {
    y = i ? y + list[i - 1].rows[1] - f.rows[0] + 1 + GAP : -f.rows[0];
    return { f, y, top: y + f.rows[0], bottom: y + f.rows[1] };
  });
}
export const fleetCells = (list) => fleetLanes(list).flatMap(({ f, y }) => shipPair(f.ph, f.e, f.dy).map(([x, c]) => [x, c + y]));

