// Head-on: two free ships flying straight at each other. Every way they can meet is
// classified below.
import { SHIP } from './abreast.js';

// Ship A is SHIP[0] (abreast.js), flying +x, nose at column 8. Ship B is its mirror
// image flying -x, `ph` generations into its own flight: SHIP[ph] reflected so that its
// path starts with its nose at column X0 + t - 8, then moved `dy` rows down. Its cells at
// generation g lie in columns X0 + t - (g + ph) - 8 .. X0 + t - (g + ph) + 6 (a lone
// ship's span, reflected; tested).
//
// Every timing: moving B twelve columns further off gives exactly the same meeting six
// generations later (A has flown six on, B six back, and both are in the phase they
// started in), so t = 0 .. 11 with ph = 0 .. 5 covers every way two ships can approach
// each other. X0 is far enough that nothing passes between them at generation 0.
// Every phase of the ship is its own mirror image about row 2.5 (tested in
// abreast.test.mjs), so dy and -dy are mirror images: dy >= 0 covers both. Beyond
// DY rows across, two empty rows always lie between them and they never touch.
export const X0 = 24, T = 12, DY = 11;
export const headB = (ph, t, dy) => SHIP[ph].map(([x, y]) => [X0 + t - x, y + dy]);
export const headPair = (ph, t, dy) => [...SHIP[0], ...headB(ph, t, dy)];
// The mirror image of meeting (ph, t) (the whole plane turned half round, which turns
// each ship into the other) is (6 - ph, t + 6), or itself when ph = 0 (tested by turning
// every meeting round and finding it in the map).
export const mirror = (ph, t) => (ph ? [6 - ph, (t + 6) % T] : [0, t]);
export const outcomeAt = (ph, t, dy) => {
  const c = MAP[Math.abs(dy)]?.[ph * T + t];
  return c === 'o' ? OUT[`${ph},${t},${Math.abs(dy)}`] : c;
};

