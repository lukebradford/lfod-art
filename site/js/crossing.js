// Crossing: two free ships flying at right angles. Every way their paths can cross is
// classified below.
import { SHIP } from './abreast.js';

// Ship A is SHIP[0] (abreast.js), flying +x (right), nose at column 8, in rows 0..5.
// Ship B is the same ship turned to fly +y (down the screen): SHIP[ph] reflected in the
// diagonal (every phase is its own mirror image about row 2.5, so this is a turn), `ph`
// generations into its own flight, its path in columns bx .. bx + 5 (bx = X + u), and its
// nose in row by + 8 (by = -bx - d). A's nose reaches B's path (column bx) at generation
// bx - 8; B's nose reaches A's path (row 0) at generation bx + d - 8. So d is B's lag:
// how many generations after A gets to the crossing B gets there (negative: B is first).
//
// A lone ship's cells at generation g lie in columns g - 6 .. g + 8 and rows -2 .. 7
// (tested in abreast.test.mjs), so B's lie in columns bx - 2 .. bx + 7 and rows
// by + g - 6 .. by + g + 8. When |d| > D they never touch (tested to 27; beyond that the
// two ranges never come within reach of each other at any generation).
// Every timing: B six columns left and six rows lower is the same crossing six
// generations later (both ships in the phase they started in), so u = 0 .. 5 with
// ph = 0 .. 5 covers every way two ships can cross. X is far enough ahead of A that
// nothing passes between them at generation 0.
export const X = 18, D = 21;
export const crossB = (ph, u, d) => SHIP[ph].map(([x, y]) => [X + u + y, -(X + u) - d + x - ph]);
export const crossPair = (ph, u, d) => [...SHIP[0], ...crossB(ph, u, d)];
// The mirror image of crossing (ph, u, d) (the plane reflected in the diagonal, which
// swaps the two ships' roles, so B's lag becomes A's) is (6 - ph, u + ph + d, -d), phases
// and timings mod 6. Found by reflecting every crossing and finding it in another's run
// (tested). Applied twice it gives back (ph, u, d).
const mod6 = (n) => ((n % 6) + 6) % 6;
export const mirror = (ph, u, d) => [mod6(6 - ph), mod6(u + ph + d), -d];
export const outcomeAt = (ph, u, d) => {
  const c = MAP[ph * 6 + u]?.[d + D];
  if (c === undefined) return '.';
  return c === 'o' ? OUT[`${ph},${u},${d}`] : c;
};

